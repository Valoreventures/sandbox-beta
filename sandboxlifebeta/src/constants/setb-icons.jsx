// Helper function to get special treatment icons
export const getSpecialTreatmentIcons = () => {
  return setb_preview_icons.filter(icon => icon.special_treatment);
};

// Helper function to get regular icons
export const getRegularIcons = () => {
  return setb_preview_icons.filter(icon => !icon.special_treatment);
};

// Helper function to get icon by UUID
export const getIconByUuid = (uuid) => {
  return setb_preview_icons.find(icon => icon.uuid === uuid);
};

